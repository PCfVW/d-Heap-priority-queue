//! Walks `benchmarks/results/<Language>/*.{jsonl,stats.json,rss.json,profile.jsonl}`
//! and groups every record by its natural key. Aggregation must be
//! deterministic given the same inputs (per methodology.md) — grouping by key
//! rather than "latest file wins" and iterating `BTreeMap`s (sorted) rather
//! than `HashMap`s (iteration-order-unstable) gets that for free.

use anyhow::{bail, Context, Result};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::path::Path;

/// The five language result subdirectories, in the fixed column order every
/// report table uses.
pub const LANGUAGES: [&str; 5] = ["Cpp", "Go", "Rust", "TypeScript", "Zig"];

/// The eight benchmark corpus graphs, in methodology.md's fixed order.
pub const GRAPHS: [&str; 8] = [
    "small",
    "medium_sparse",
    "medium_dense",
    "medium_grid",
    "large_sparse",
    "large_dense",
    "large_grid",
    "huge_dense",
];

/// The three heap arities every cell is measured at.
pub const ARITIES: [u32; 3] = [2, 4, 8];

#[derive(Deserialize)]
struct WallTimeRecord {
    language: String,
    graph: String,
    arity: u32,
    wall_time_us: f64,
}

#[derive(Deserialize)]
struct StatsRecord {
    language: String,
    graph: String,
    arity: u32,
    comparison_counts: CompCounts,
}

#[derive(Deserialize)]
struct CompCounts {
    total: u64,
}

#[derive(Deserialize)]
struct RssRecord {
    language: String,
    arity: u32,
    peak_rss_kb: u64,
}

#[derive(Deserialize)]
struct ProfileRecord {
    language: String,
    graph: String,
    arity: u32,
    section_us: SectionUs,
}

/// One `--profile-sections` record's four timed sections plus their sum, in
/// microseconds — one rep out of the K=2 warmup / N=10 repeated protocol
/// (`benchmarks/methodology.md`, "Phase 3.5"). Field names mirror
/// `section_us` in the JSON schema exactly; the record's own `rep` field
/// isn't captured here — reps are accumulated into a `Vec` by insertion
/// order (see [`Dataset::sections`]) and [`crate::stats::compute`] doesn't
/// care which rep produced which sample.
#[derive(Deserialize, Clone, Copy)]
pub struct SectionUs {
    pub setup: f64,
    pub pop: f64,
    pub relax: f64,
    pub inc_pri: f64,
    pub total: f64,
}

/// A `(graph, arity)` pair — the natural grouping key for every result type
/// except peak RSS, which is `huge_dense`-only and keyed by `(language, arity)`.
pub type CellKey = (String, u32);

/// Every parsed result file, grouped by key. Empty `BTreeMap`s are valid —
/// callers report missing data explicitly rather than the collector guessing
/// at defaults.
#[derive(Default)]
pub struct Dataset {
    /// `(graph, arity) -> language -> the 10 wall_time_us samples`.
    pub wall_times: BTreeMap<CellKey, BTreeMap<String, Vec<f64>>>,
    /// `(graph, arity) -> language -> comparison-count total`.
    pub comparison_totals: BTreeMap<CellKey, BTreeMap<String, u64>>,
    /// `(language, arity) -> peak RSS in KB` (`huge_dense` only).
    pub rss_kb: BTreeMap<(String, u32), u64>,
    /// `(graph, arity) -> language -> the 10 section-timing samples` (Phase 3.5).
    pub sections: BTreeMap<CellKey, BTreeMap<String, Vec<SectionUs>>>,
}

/// Reads every result file under `results_dir/<Language>/` for each of the
/// five [`LANGUAGES`] and folds them into a [`Dataset`].
///
/// # Errors
/// Returns an error if a language's results directory is missing, a file
/// can't be read, or a file's content doesn't match its expected schema.
pub fn collect(results_dir: &Path) -> Result<Dataset> {
    let mut ds = Dataset::default();

    for lang in LANGUAGES {
        let dir = results_dir.join(lang);
        if !dir.is_dir() {
            bail!(
                "missing results directory: {} (expected one subdirectory per language)",
                dir.display()
            );
        }

        let entries = std::fs::read_dir(&dir)
            .with_context(|| format!("reading directory {}", dir.display()))?;

        for entry in entries {
            let path = entry?.path();
            let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
                continue;
            };

            // Multi-part suffixes (`.stats.json`, `.rss.json`, `.profile.json`)
            // rule out `Path::extension()`, which only ever returns the last
            // component (`json` for all three) — a plain, case-sensitive
            // `ends_with` is the correct tool here, not an approximation of
            // it; every file this collector writes/reads is generated by
            // this project's own tooling with a fixed lowercase suffix, so
            // case-insensitivity buys nothing.
            #[allow(clippy::case_sensitive_file_extension_comparisons)]
            if name.ends_with(".profile.jsonl") {
                // Must be checked before the plain `.jsonl` arm below —
                // `.profile.jsonl` ends with `.jsonl` too.
                let text = std::fs::read_to_string(&path)
                    .with_context(|| format!("reading {}", path.display()))?;
                for line in text.lines().filter(|l| !l.trim().is_empty()) {
                    let rec: ProfileRecord = serde_json::from_str(line)
                        .with_context(|| format!("parsing a line of {}", path.display()))?;
                    ds.sections
                        .entry((rec.graph.clone(), rec.arity))
                        .or_default()
                        .entry(rec.language.clone())
                        .or_default()
                        .push(rec.section_us);
                }
            } else if name.ends_with(".jsonl") {
                let text = std::fs::read_to_string(&path)
                    .with_context(|| format!("reading {}", path.display()))?;
                for line in text.lines().filter(|l| !l.trim().is_empty()) {
                    let rec: WallTimeRecord = serde_json::from_str(line)
                        .with_context(|| format!("parsing a line of {}", path.display()))?;
                    ds.wall_times
                        .entry((rec.graph.clone(), rec.arity))
                        .or_default()
                        .entry(rec.language.clone())
                        .or_default()
                        .push(rec.wall_time_us);
                }
            } else if name.ends_with(".stats.json") {
                let text = std::fs::read_to_string(&path)
                    .with_context(|| format!("reading {}", path.display()))?;
                let rec: StatsRecord = serde_json::from_str(&text)
                    .with_context(|| format!("parsing {}", path.display()))?;
                ds.comparison_totals
                    .entry((rec.graph.clone(), rec.arity))
                    .or_default()
                    .insert(rec.language.clone(), rec.comparison_counts.total);
            } else if name.ends_with(".rss.json") {
                let text = std::fs::read_to_string(&path)
                    .with_context(|| format!("reading {}", path.display()))?;
                let rec: RssRecord = serde_json::from_str(&text)
                    .with_context(|| format!("parsing {}", path.display()))?;
                ds.rss_kb.insert((rec.language, rec.arity), rec.peak_rss_kb);
            }
        }
    }

    Ok(ds)
}

/// Verifies the Phase 2 cross-language invariant: the comparison-count
/// `total` for a given `(graph, arity)` must be byte-identical across all
/// five languages. A divergence is a bug, not benchmark variance — per
/// methodology.md, the aggregator must exit non-zero on disagreement rather
/// than silently reporting mismatched numbers.
///
/// # Errors
/// Returns an error listing every `(graph, arity)` cell where the totals
/// disagree, or where a language's data is missing for a cell that has data
/// from at least one other language.
pub fn check_comparison_invariant(ds: &Dataset) -> Result<()> {
    let mut problems = Vec::new();

    for (key, by_lang) in &ds.comparison_totals {
        let mut totals: Vec<(&String, u64)> = by_lang.iter().map(|(l, t)| (l, *t)).collect();
        totals.sort();

        let missing: Vec<&str> = LANGUAGES
            .iter()
            .filter(|l| !by_lang.contains_key(**l))
            .copied()
            .collect();
        if !missing.is_empty() {
            problems.push(format!(
                "{}/d={}: missing comparison-count data for {}",
                key.0,
                key.1,
                missing.join(", ")
            ));
            continue;
        }

        let first_total = totals[0].1;
        if totals.iter().any(|(_, t)| *t != first_total) {
            let detail = totals
                .iter()
                .map(|(l, t)| format!("{l}={t}"))
                .collect::<Vec<_>>()
                .join(", ");
            problems.push(format!("{}/d={}: {}", key.0, key.1, detail));
        }
    }

    if problems.is_empty() {
        Ok(())
    } else {
        bail!(
            "comparison-count invariant violated on {} cell(s):\n  {}",
            problems.len(),
            problems.join("\n  ")
        );
    }
}
